class Command(BaseCommand):
    help = "Create or refresh the initial Khosh Visa content."

    def handle(self, *args, **options):
        SiteSettings.objects.update_or_create(
            pk=1,
            defaults={
                "brand_name": "خوش ویزا",
                "mobile": "09124175574",
                "phone": "02146010788",
                "north_office": "تهران، قبل از پارک‌وی، روبه‌روی هتل استقلال",
                "west_office": "تهران، جنت‌آباد مرکزی، بلوار بعثت",
            },
        )
        for order, row in enumerate(LANDINGS, start=1):
            page_type, title, slug, excerpt, body, meta_title, meta_description = row
            LandingPage.objects.update_or_create(
                slug=slug,
                defaults={
                    "page_type": page_type,
                    "title": title,
                    "excerpt": excerpt,
                    "body": body,
                    "meta_title": meta_title,
                    "meta_description": meta_description,
                    "is_published": True,
                    "sort_order": order,
                },
            )
        self.stdout.write(self.style.SUCCESS("محتوای اولیه خوش ویزا ایجاد یا به‌روزرسانی شد."))

